import { defineConfig, lazyPlugins } from "vite-plus";
import { jevApiPlugin } from "./server/jev-api.ts";

/**
 * Varlock resolves TYPESAFE_API_KEY from 1Password, which can wait on a desktop-app
 * prompt. Only the dev and preview servers need the key (the `/api/jev` middleware
 * reads it per request), so the client build, unit tests, and metadata reads (check,
 * lint, fmt) skip the plugin. It loads the env as soon as its module is imported,
 * hence the dynamic import.
 *
 * Spike (issue #1): the Worker in `worker/` runs through `@cloudflare/vite-plugin`.
 * The dev and preview servers get it wrapped by `varlockCloudflareVitePlugin`, which
 * also runs `varlock load` on import, so it stays behind the same gate. The build
 * gets the plain Cloudflare plugin, which needs no secrets. `jevApiPlugin` comes
 * first so its `/api/jev` middleware runs before the Cloudflare plugin sends every
 * other `/api/*` request to the Worker.
 */
export default defineConfig(({ command }) => {
  const servesApi = command === "serve" && !process.env.VITEST;
  const buildsWorker = command === "build" && !process.env.VITEST;
  return {
    plugins: lazyPlugins(async () => {
      if (servesApi) {
        const { varlockCloudflareVitePlugin } = await import("@varlock/cloudflare-integration");
        return [jevApiPlugin(), varlockCloudflareVitePlugin()];
      }
      if (buildsWorker) {
        const { cloudflare } = await import("@cloudflare/vite-plugin");
        return [jevApiPlugin(), cloudflare()];
      }
      return [jevApiPlugin()];
    }),
    staged: {
      "*": "vp check --fix",
    },
    // env.d.ts is regenerated by Varlock on every dev-server start, in its own formatting.
    // worker/worker-configuration.d.ts is generated by `wrangler types`.
    fmt: { ignorePatterns: ["env.d.ts", "worker/worker-configuration.d.ts"] },
    lint: {
      ignorePatterns: ["worker/worker-configuration.d.ts"],
      jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
      rules: { "vite-plus/prefer-vite-plus-imports": "error" },
      options: { typeAware: true, typeCheck: true },
    },
  };
});
