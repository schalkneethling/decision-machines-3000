import { defineConfig, lazyPlugins } from "vite-plus";
import { viteHostPlugin } from "./server/vite-host.ts";

/**
 * The plugins follow ADR-0001 (path A), behind a gate that keeps 1Password out of
 * every command except the dev and preview servers.
 *
 * - `vp dev` and `vp preview` load `varlockCloudflareVitePlugin`, which wraps
 *   `@cloudflare/vite-plugin`, runs the Worker in workerd, and gives it and this
 *   Node process the Varlock-resolved environment. Importing its module runs
 *   `varlock load` at once, which can wait on a 1Password prompt, hence the
 *   dynamic import.
 * - `vp build` loads the plain Cloudflare plugin, which needs no secrets and
 *   writes what `wrangler deploy` needs.
 * - Unit tests and metadata reads (check, lint, fmt) load neither.
 *
 * Order matters, because the plugin listed first sees each request first:
 * `viteHostPlugin` (dev only) answers every `/api` path with the Worker's
 * `handle` in Node, and the Cloudflare plugin serves everything else. Nothing
 * mounts the old `/api/jev` middleware any more; its paths answer a JSON 404.
 */
export default defineConfig(({ command }) => {
  const servesApi = command === "serve" && !process.env.VITEST;
  const buildsWorker = command === "build" && !process.env.VITEST;
  return {
    plugins: lazyPlugins(async () => {
      if (servesApi) {
        const { varlockCloudflareVitePlugin } = await import("@varlock/cloudflare-integration");
        return [viteHostPlugin(), varlockCloudflareVitePlugin()];
      }
      if (buildsWorker) {
        const { cloudflare } = await import("@cloudflare/vite-plugin");
        return [cloudflare()];
      }
      return [];
    }),
    staged: {
      "*": "vp check --fix",
    },
    // env.d.ts is regenerated by Varlock on every dev-server start, in its own formatting.
    // worker/worker-configuration.d.ts is generated by `wrangler types`.
    fmt: { ignorePatterns: ["env.d.ts", "worker/worker-configuration.d.ts"] },
    lint: {
      jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
      // Both files are generated and declare interfaces for declaration merging, so
      // they are ignored here instead of being edited by hand: env.d.ts by Varlock,
      // and worker/worker-configuration.d.ts by `wrangler types`.
      ignorePatterns: ["env.d.ts", "worker/worker-configuration.d.ts"],
      rules: {
        "vite-plus/prefer-vite-plus-imports": "error",
        "typescript/consistent-type-definitions": ["error", "type"],
      },
      options: { typeAware: true, typeCheck: true },
    },
  };
});
